#!/usr/bin/env python3
"""Cosmetic, SOUTH-authored connected tiles. Leaves legacy physics/assets untouched.

Run from anywhere with Python 3 (standard library only). A single periodic strip
is clipped, never scaled, into cells. Mask bits: left=1, right=2, down=4, up=8.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEST = ROOT / 'src/main/resources/assets/whiteout/models/block'
# Existing pair-0 proportions, displaced by 2px so vertical joins cut real boards.
# The 32px strip repeats; uneven widths, gaps and alternating depth remain deliberate.
BOARDS = [(3, 8, 14, 16), (10, 15, 13, 15), (16.5, 21.5, 14, 16),
          (23, 28, 13, 15), (29.5, 33.5, 14, 16)]

def box(x0, y0, z0, x1, y1, z1, texture, mask, v0=0, v1=16):
    faces = {f: {'texture': texture} for f in ('north', 'south', 'west', 'east', 'up', 'down')}
    # Continuous grain: each board samples the same grain band, including across a Y cut.
    faces['south']['uv'] = [x0, v0, x1, v1]
    faces['north']['uv'] = [16-x1, v0, 16-x0, v1]
    for face, bit, at_edge in [('west', 1, x0 == 0), ('east', 2, x1 == 16),
                               ('down', 4, y0 == 0), ('up', 8, y1 == 16)]:
        if mask & bit and at_edge:
            del faces[face]  # No opposing coplanar internal caps.
    return {'from': [x0, y0, z0], 'to': [x1, y1, z1], 'faces': faces}

def model(phase, mask):
    lo, hi = phase * 16, (phase + 1) * 16
    elements = []
    for shift in (-32, 0, 32):
        for index, (bottom, top, back, front) in enumerate(BOARDS):
            bottom += shift
            top += shift
            a, b = max(lo, bottom), min(hi, top)
            if a >= b:
                continue
            # Small irregularities only at exposed ends; shared edges are exact.
            inset = (0.125, 0.25, 0.0625, 0.1875, 0.125)[index]
            left = 0 if mask & 1 else inset
            right = 16 if mask & 2 else 16-inset
            v0 = .25 + (top-b)/(top-bottom)*2.5
            v1 = .25 + (top-a)/(top-bottom)*2.5
            elements.append(box(left, a-lo, back, right, b-lo, front, '#wood', mask, v0, v1))
            # Nail heads belong to the full board, not to each clipped fragment.
            # A wide board is nailed at its outer frame, never at every block seam.
            center = (bottom+top)/2
            if (bottom < lo and not mask & 4) or (top > hi and not mask & 8):
                center = (a+b)/2  # Exposed clipped end still needs a fastening point.
            na, nb = max(lo, center-.4), min(hi, center+.4)
            if na >= nb:
                continue
            for x, bit in ((1.5, 1), (14.5, 2)):
                if not mask & bit:
                    elements.append(box(x-.4, na-lo, front, x+.4, nb-lo, front+.2,
                                        '#iron', mask))
    return {'ambientocclusion': False,
            'textures': {'wood': 'whiteout:block/barricade_planks',
                         'iron': 'whiteout:block/barricade_nail', 'particle': '#wood'},
            'elements': elements}

def collision_source():
    rows = []
    for phase in range(2):
        masks = []
        for mask in range(16):
            boxes = [e['from'] + e['to'] for e in model(phase, mask)['elements']
                     if e['faces']['south']['texture'] == '#wood']
            masks.append('  {' + ','.join('{' + ','.join(str(v) for v in b) + '}' for b in boxes) + '}')
        rows.append(' {\n' + ',\n'.join(masks) + '\n }')
    return ('package dev.whiteout.power.barricade;\n'
            '/** Generated by tools/make_connected_barricades.py; wood only, no nail collision. */\n'
            'final class ConnectedBarricadeLayouts {\n'
            ' private ConnectedBarricadeLayouts(){}\n'
            ' static final double[][][][] BOXES={\n' + ',\n'.join(rows) + '\n };\n}\n')

def main():
    DEST.mkdir(parents=True, exist_ok=True)
    for phase in range(2):
        for mask in range(16):
            (DEST / f'barricade_connected_{phase}_{mask}.json').write_text(
                json.dumps(model(phase, mask), indent=1)+'\n', encoding='utf-8')
    (ROOT / 'src/main/java/dev/whiteout/power/barricade/ConnectedBarricadeLayouts.java').write_text(
        collision_source(), encoding='utf-8')
    print('Generated 32 connected models and matching collision layouts.')

if __name__ == '__main__':
    main()
