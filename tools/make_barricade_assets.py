#!/usr/bin/env python3
"""Single source of truth for barricade geometry.
Generates: block models, blockstate, item model, textures and BarricadeLayouts.java
(collision shapes + coverage table) so visuals and physics can never drift apart.
Layouts are authored for the plate on the SOUTH side of the cell (z 11..16) in pixels;
the pair layouts are authored in 2-cell space (y 0..32) and split per cell.
Run from the repo root:  python3 tools/make_barricade_assets.py
To add a new opening size: add layouts + a Part value in BarricadeBlock.Part and an OpeningShape."""
import json, os, random
from PIL import Image

ROOT = os.path.join(os.path.dirname(__file__), '..', 'src', 'main')
RES = os.path.join(ROOT, 'resources', 'assets', 'whiteout')
JAVA = os.path.join(ROOT, 'java', 'dev', 'whiteout', 'power', 'barricade', 'BarricadeLayouts.java')

SINGLE = [
 [(0,1,14,16,5,16),(0,6,13,16,10,15),(0,11,14,16,15,16)],
 [(0,2,14,16,7.5,16),(0,9,13,16,14,15)],
 [(0,0,14,16,3.5,16),(0,4.5,13,16,8,15),(0,9,14,16,12.5,16),(0,13.5,13,16,16,15)],
]
PAIR = [
 [(0,1,14,16,6,16),(0,8,13,16,13,15),(0,14.5,14,16,19.5,16),(0,21,13,16,26,15),(0,27.5,14,16,31.5,16)],
 [(0,0,14,16,7,16),(0,9,13,16,15,15),(0,17,14,16,22.5,16),(0,24,13,16,31,15)],
 [(0,2,13,16,7,15),(0,8.5,14,16,13.5,16),(0,15,13,16,20,15),(0,21.5,14,16,26.5,16),(0,28,13,16,32,15)],
]

def split(layout, lo, hi):
    """Returns boards clipped to [lo,hi], shifted into cell coordinates.
    The old full-height back battens have deliberately been removed: they poked
    above/below boards and looked like visual artifacts in narrow openings."""
    boards, battens, batten = [], [], False
    for b in layout:
        if b == 'B': batten = True; continue
        y0, y1 = max(b[1], lo), min(b[4], hi)
        if y1 - y0 < 0.05: continue
        c = (b[0], y0 - lo, b[2], b[3], y1 - lo, b[5])
        (battens if batten else boards).append(c)
    return boards, battens

def parts():
    out = {'single': [], 'bottom': [], 'top': []}
    for v in range(3):
        out['single'].append(split(SINGLE[v], 0, 16))
        out['bottom'].append(split(PAIR[v], 0, 16))
        out['top'].append(split(PAIR[v], 16, 32))
    return out

def nails(boards):
    res = []
    for (x0, y0, z0, x1, y1, z1) in boards:
        cy = (y0 + y1) / 2
        if y1 - y0 < 2: continue
        for nx in (1.5, 13.0):
            res.append((nx, cy - .75, z1, nx + 1.5, cy + .75, z1 + .5))
    return res

def face_block(t): return {f: {"texture": t} for f in ("north", "east", "south", "west", "up", "down")}
def elem(b, tex): return {"from": [b[0], b[1], b[2]], "to": [b[3], b[4], b[5]], "faces": face_block(tex)}

def write(path, data, mode='w'):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, mode) as f: f.write(data)

def gen_models():
    P = parts()
    for name, variants in P.items():
        for v, (boards, battens) in enumerate(variants):
            els = [elem(b, '#wood') for b in boards + battens] + [elem(n, '#iron') for n in nails(boards)]
            model = {"textures": {"wood": "whiteout:block/barricade_planks", "iron": "whiteout:block/barricade_nail",
                                  "particle": "#wood"}, "elements": els}
            write(f'{RES}/models/block/barricade_{name}_{v}.json', json.dumps(model, indent=1))
    rot = {'south': 0, 'west': 90, 'north': 180, 'east': 270}
    variants = {}
    for f, y in rot.items():
        for name in P:
            for v in range(3):
                e = {"model": f"whiteout:block/barricade_{name}_{v}"}
                if y: e["y"] = y
                variants[f"facing={f},part={name},variant={v}"] = e
    write(f'{RES}/blockstates/barricade.json', json.dumps({"variants": variants}, indent=1))
    write(f'{RES}/models/item/barricade_boards.json', json.dumps(
        {"parent": "minecraft:item/generated", "textures": {"layer0": "whiteout:item/barricade_boards"}}, indent=1))

def fmt(v): return repr(float(v))

def gen_java():
    P = parts(); order = ['single', 'bottom', 'top']
    lines = ["package dev.whiteout.power.barricade;", "",
             "/** GENERATED by tools/make_barricade_assets.py - do not edit by hand.",
             " *  Collision boxes (pixels, plate on the SOUTH side) and frontal coverage per [part][variant]. */",
             "final class BarricadeLayouts {", " private BarricadeLayouts(){}",
             " /** [part SINGLE,BOTTOM,TOP][variant 0..2][box]{x0,y0,z0,x1,y1,z1} - boards and battens, nails excluded. */",
             " static final double[][][][] BOXES={"]
    cov = []
    for name in order:
        lines.append("  {")
        crow = []
        for boards, battens in P[name]:
            allb = boards + battens
            lines.append("   {" + ",".join("{" + ",".join(fmt(x) for x in b) + "}" for b in allb) + "},")
            # Exact coverage: 64x64 samples (0.25 px). Board edges lie on multiples of 0.25, sample centres never do.
            cells = 0
            for yy in range(64):
                for xx in range(64):
                    px, py = (xx + .5) / 4, (yy + .5) / 4
                    if any(b[0] < px < b[3] and b[1] < py < b[4] for b in allb): cells += 1
            crow.append(cells / 4096.0)
        lines.append("  },"); cov.append(crow)
    lines += [" };", " /** Share of the cell cross-section blocked by wood, [part][variant]. */",
              " static final double[][] COVERAGE={" + ",".join("{" + ",".join(fmt(c) for c in r) + "}" for r in cov) + "};", "}", ""]
    write(JAVA, "\n".join(lines))
    print('coverage', cov)

def gen_textures():
    random.seed(11)
    im = Image.new('RGBA', (16, 16))
    base = (112, 96, 78)
    for y in range(16):
        for x in range(16):
            g = random.randint(-9, 9) + (10 if (y // 4) % 2 else -4)
            if x % 5 == 2 and random.random() < .5: g -= 14      # grain streak
            c = tuple(max(0, min(255, v + g)) for v in base)
            im.putpixel((x, y), c + (255,))
    for y in (0, 3, 7, 11, 15):
        for x in range(16): im.putpixel((x, y), (66, 56, 46, 255))   # board seams
    write(f'{RES}/textures/block/barricade_planks.png', b'', 'wb'); im.save(f'{RES}/textures/block/barricade_planks.png')
    nail = Image.new('RGBA', (16, 16), (52, 50, 50, 255))
    for y in range(16):
        for x in range(16):
            if (x + y) % 5 == 0: nail.putpixel((x, y), (96, 82, 70, 255))
    nail.save(f'{RES}/textures/block/barricade_nail.png')
    ic = Image.new('RGBA', (16, 16), (0, 0, 0, 0))
    for (y0, y1, off) in ((2, 5, 0), (6, 9, 1), (10, 13, 0)):
        for y in range(y0, y1 + 1):
            for x in range(1 + off, 15):
                g = random.randint(-8, 8)
                ic.putpixel((x, y), tuple(max(0, min(255, v + g)) for v in base) + (255,))
        for x in range(1 + off, 15): ic.putpixel((x, y1), (66, 56, 46, 255))
        for nx in (3 + off, 12): ic.putpixel((nx, (y0 + y1) // 2), (40, 38, 38, 255))
    write(f'{RES}/textures/item/barricade_boards.png', b'', 'wb'); ic.save(f'{RES}/textures/item/barricade_boards.png')

if __name__ == '__main__':
    gen_models(); gen_java(); gen_textures()
